def fewshot_block() -> str:
    items = [x for x in json.loads(GOLDEN.read_text(encoding="utf-8")) if x["split"] == "fewshot"]
    return "\n".join(f'- "{x["question"]}" → {", ".join(x["categories"])}' for x in items)


